// Package gen generates Go source code from a compiled OCSF schema.
//
// It emits two packages: an objects package holding a struct per (non-hidden)
// OCSF object, and an events package holding a struct per event class plus
// class/category UID constants. Event structs reference object structs via an
// import of the objects package, because several OCSF names (e.g.
// "application", "remediation") exist as both an object and an event class.
package gen

import (
	"encoding/json"
	"fmt"
	"go/format"
	"html"
	"maps"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/grokify/ocsf-schema-go/schema"
)

// Options configures code generation.
type Options struct {
	// ObjectsPackage and EventsPackage are the generated package names.
	// They default to "objects" and "events".
	ObjectsPackage string
	EventsPackage  string
	// ObjectsImportPath is the full import path of the objects package,
	// referenced by the generated events package.
	ObjectsImportPath string
	// SchemaImportPath is the import path of this module's schema package,
	// referenced by the generated ocsfdata package.
	SchemaImportPath string
	// SkipData disables generation of the embedded compiled schema
	// (ocsfdata package).
	SkipData bool
}

func (o *Options) setDefaults() {
	if o.ObjectsPackage == "" {
		o.ObjectsPackage = "objects"
	}
	if o.EventsPackage == "" {
		o.EventsPackage = "events"
	}
	if o.ObjectsImportPath == "" {
		o.ObjectsImportPath = "github.com/grokify/ocsf-schema-go/ocsf/objects"
	}
	if o.SchemaImportPath == "" {
		o.SchemaImportPath = "github.com/grokify/ocsf-schema-go/schema"
	}
}

// Generate produces gofmt-formatted Go source files from the compiled
// schema. The result maps relative output paths (e.g. "objects/objects.go",
// "events/iam.go") to file contents.
func Generate(c *schema.CompiledSchema, opts Options) (map[string][]byte, error) {
	opts.setDefaults()
	g := &generator{c: c, opts: opts}
	return g.generate()
}

type generator struct {
	c    *schema.CompiledSchema
	opts Options
}

func (g *generator) generate() (map[string][]byte, error) {
	files := map[string][]byte{}

	src, err := g.objectsFile()
	if err != nil {
		return nil, err
	}
	files[g.opts.ObjectsPackage+"/objects.go"] = src

	eventFiles, err := g.eventFiles()
	if err != nil {
		return nil, err
	}
	for name, content := range eventFiles {
		files[g.opts.EventsPackage+"/"+name] = content
	}

	constSrc, err := g.constantsFile()
	if err != nil {
		return nil, err
	}
	files[g.opts.EventsPackage+"/constants.go"] = constSrc

	registrySrc, err := g.registryFile()
	if err != nil {
		return nil, err
	}
	files[g.opts.EventsPackage+"/registry.go"] = registrySrc

	obsSrc, err := g.observablesFile()
	if err != nil {
		return nil, err
	}
	files[g.opts.ObjectsPackage+"/observables.go"] = obsSrc

	if !g.opts.SkipData {
		dataFiles, err := g.ocsfdataFiles()
		if err != nil {
			return nil, err
		}
		maps.Copy(files, dataFiles)
	}

	objDoc, err := g.docFile(g.opts.ObjectsPackage,
		fmt.Sprintf("Package %s contains generated Go structs for OCSF objects.", g.opts.ObjectsPackage))
	if err != nil {
		return nil, err
	}
	files[g.opts.ObjectsPackage+"/doc.go"] = objDoc

	evtDoc, err := g.docFile(g.opts.EventsPackage,
		fmt.Sprintf("Package %s contains generated Go structs for OCSF event classes.", g.opts.EventsPackage))
	if err != nil {
		return nil, err
	}
	files[g.opts.EventsPackage+"/doc.go"] = evtDoc

	return files, nil
}

// docFile renders a doc.go carrying the package comment, kept separate so
// that per-category files need no package docs of their own.
func (g *generator) docFile(pkg, doc string) ([]byte, error) {
	b := &strings.Builder{}
	fmt.Fprintf(b, "// Code generated by ocsfgen from OCSF schema v%s; DO NOT EDIT.\n", g.c.Version)
	b.WriteString("// Source: https://github.com/ocsf/ocsf-schema\n\n")
	writeComment(b, doc)
	writeComment(b, fmt.Sprintf("Generated from OCSF schema version %s.", g.c.Version))
	fmt.Fprintf(b, "package %s\n", pkg)
	return formatSource(b.String())
}

func (g *generator) header(b *strings.Builder, pkg string) {
	fmt.Fprintf(b, "// Code generated by ocsfgen from OCSF schema v%s; DO NOT EDIT.\n", g.c.Version)
	b.WriteString("// Source: https://github.com/ocsf/ocsf-schema\n\n")
	fmt.Fprintf(b, "package %s\n\n", pkg)
}

// objectsFile renders every non-hidden object into a single file.
func (g *generator) objectsFile() ([]byte, error) {
	names := make([]string, 0, len(g.c.Objects))
	for name, obj := range g.c.Objects {
		if !obj.Hidden {
			names = append(names, name)
		}
	}
	sort.Strings(names)

	b := &strings.Builder{}
	g.header(b, g.opts.ObjectsPackage)

	for _, name := range names {
		obj := g.c.Objects[name]
		doc := fmt.Sprintf("%s is the OCSF %q object.", GoName(name), name)
		if err := g.writeStruct(b, GoName(name), doc, obj.Description, obj.Deprecated, obj.Attributes, false); err != nil {
			return nil, fmt.Errorf("object %s: %w", name, err)
		}
	}
	return formatSource(b.String())
}

// eventFiles renders event classes grouped one file per category.
func (g *generator) eventFiles() (map[string][]byte, error) {
	byCategory := map[string][]string{}
	for name, cls := range g.c.Classes {
		cat := cls.Category
		if cat == "" || cat == "other" {
			cat = "base"
		}
		byCategory[cat] = append(byCategory[cat], name)
	}

	files := map[string][]byte{}
	for cat, classNames := range byCategory {
		sort.Strings(classNames)
		b := &strings.Builder{}
		g.header(b, g.opts.EventsPackage)

		usesObjects := false
		for _, name := range classNames {
			if g.classReferencesObjects(g.c.Classes[name]) {
				usesObjects = true
				break
			}
		}
		if usesObjects {
			fmt.Fprintf(b, "import %q\n\n", g.opts.ObjectsImportPath)
		}

		for _, name := range classNames {
			cls := g.c.Classes[name]
			var doc string
			switch {
			case cls.Abstract:
				doc = fmt.Sprintf("%s is the OCSF %q event class (abstract base class).", GoName(name), name)
			default:
				doc = fmt.Sprintf("%s is the OCSF %q event class (class_uid %d).", GoName(name), name, cls.ClassUID)
			}
			if err := g.writeStruct(b, GoName(name), doc, cls.Description, cls.Deprecated, cls.Attributes, true); err != nil {
				return nil, fmt.Errorf("event class %s: %w", name, err)
			}
		}

		src, err := formatSource(b.String())
		if err != nil {
			return nil, fmt.Errorf("category %s: %w", cat, err)
		}
		files[cat+".go"] = src
	}
	return files, nil
}

func (g *generator) classReferencesObjects(cls *schema.CompiledClass) bool {
	for _, attr := range cls.Attributes {
		if _, ok := g.c.Objects[attr.Type]; ok {
			return true
		}
	}
	return false
}

// constantsFile renders SchemaVersion plus category and class UID constants.
func (g *generator) constantsFile() ([]byte, error) {
	b := &strings.Builder{}
	g.header(b, g.opts.EventsPackage)

	b.WriteString("// SchemaVersion is the OCSF schema version these bindings were generated from.\n")
	fmt.Fprintf(b, "const SchemaVersion = %q\n\n", g.c.Version)

	catNames := make([]string, 0, len(g.c.Categories))
	for name := range g.c.Categories {
		catNames = append(catNames, name)
	}
	sort.Slice(catNames, func(i, j int) bool {
		return g.c.Categories[catNames[i]].UID < g.c.Categories[catNames[j]].UID
	})
	b.WriteString("// Category unique identifiers (category_uid).\nconst (\n")
	for _, name := range catNames {
		cat := g.c.Categories[name]
		fmt.Fprintf(b, "\t// %s\n\tCategoryUID%s = %d\n", cat.Caption, GoName(name), cat.UID)
	}
	b.WriteString(")\n\n")

	type classUID struct {
		name string
		uid  int
	}
	var classes []classUID
	for name, cls := range g.c.Classes {
		if !cls.Abstract {
			classes = append(classes, classUID{name, cls.ClassUID})
		}
	}
	sort.Slice(classes, func(i, j int) bool { return classes[i].uid < classes[j].uid })
	b.WriteString("// Event class unique identifiers (class_uid).\nconst (\n")
	for _, cls := range classes {
		fmt.Fprintf(b, "\t// %s\n\tClassUID%s = %d\n", g.c.Classes[cls.name].Caption, GoName(cls.name), cls.uid)
	}
	b.WriteString(")\n\n")

	// Severity and status values are uniform across event classes; emit
	// unprefixed shared constants from the base event's enums.
	if base, ok := g.c.Classes["base_event"]; ok {
		for _, shared := range []struct{ attr, prefix string }{
			{"severity_id", "SeverityID"},
			{"status_id", "StatusID"},
		} {
			attr, ok := base.Attributes[shared.attr]
			if !ok || len(attr.Enum) == 0 {
				continue
			}
			owner := fmt.Sprintf("the %s attribute shared by all event classes", shared.attr)
			if err := g.writeEnum(b, shared.prefix, owner, attr); err != nil {
				return nil, fmt.Errorf("shared enum %s: %w", shared.attr, err)
			}
		}
	}

	return formatSource(b.String())
}

// registryFile renders the class-UID registry: constructors, an unmarshal
// dispatcher, and class/category lookup maps.
func (g *generator) registryFile() ([]byte, error) {
	type classEntry struct {
		name string
		cls  *schema.CompiledClass
	}
	var classes []classEntry
	for name, cls := range g.c.Classes {
		if !cls.Abstract {
			classes = append(classes, classEntry{name, cls})
		}
	}
	sort.Slice(classes, func(i, j int) bool { return classes[i].cls.ClassUID < classes[j].cls.ClassUID })

	b := &strings.Builder{}
	g.header(b, g.opts.EventsPackage)
	b.WriteString("import (\n\t\"encoding/json\"\n\t\"fmt\"\n)\n\n")

	b.WriteString("// NewEventByClassUID returns a pointer to a zero-value event struct for the\n")
	b.WriteString("// class registered under classUID (e.g. 3002 -> *Authentication). It returns\n")
	b.WriteString("// false for class UIDs not defined by this schema version.\n")
	b.WriteString("func NewEventByClassUID(classUID int) (any, bool) {\n\tswitch classUID {\n")
	for _, e := range classes {
		fmt.Fprintf(b, "\tcase ClassUID%s:\n\t\treturn &%s{}, true\n", GoName(e.name), GoName(e.name))
	}
	b.WriteString("\t}\n\treturn nil, false\n}\n\n")

	b.WriteString("// UnmarshalEvent parses OCSF event JSON into the concrete event struct\n")
	b.WriteString("// selected by the payload's class_uid attribute.\n")
	b.WriteString("func UnmarshalEvent(data []byte) (any, error) {\n")
	b.WriteString("\tvar probe struct {\n\t\tClassUID *int `json:\"class_uid\"`\n\t}\n")
	b.WriteString("\tif err := json.Unmarshal(data, &probe); err != nil {\n\t\treturn nil, err\n\t}\n")
	b.WriteString("\tif probe.ClassUID == nil {\n\t\treturn nil, fmt.Errorf(\"ocsf: event has no class_uid attribute\")\n\t}\n")
	b.WriteString("\tevt, ok := NewEventByClassUID(*probe.ClassUID)\n")
	b.WriteString("\tif !ok {\n\t\treturn nil, fmt.Errorf(\"ocsf: unknown class_uid %d\", *probe.ClassUID)\n\t}\n")
	b.WriteString("\tif err := json.Unmarshal(data, evt); err != nil {\n\t\treturn nil, err\n\t}\n")
	b.WriteString("\treturn evt, nil\n}\n\n")

	b.WriteString("// ClassNames maps class_uid values to OCSF class names (e.g. 3002 -> \"authentication\").\n")
	b.WriteString("var ClassNames = map[int]string{\n")
	for _, e := range classes {
		fmt.Fprintf(b, "\tClassUID%s: %q,\n", GoName(e.name), e.name)
	}
	b.WriteString("}\n\n")

	b.WriteString("// ClassCaptions maps class_uid values to OCSF class captions (e.g. 3002 -> \"Authentication\").\n")
	b.WriteString("var ClassCaptions = map[int]string{\n")
	for _, e := range classes {
		fmt.Fprintf(b, "\tClassUID%s: %q,\n", GoName(e.name), e.cls.Caption)
	}
	b.WriteString("}\n\n")

	catNames := make([]string, 0, len(g.c.Categories))
	for name := range g.c.Categories {
		catNames = append(catNames, name)
	}
	sort.Slice(catNames, func(i, j int) bool {
		return g.c.Categories[catNames[i]].UID < g.c.Categories[catNames[j]].UID
	})
	b.WriteString("// CategoryCaptions maps category_uid values to OCSF category captions.\n")
	b.WriteString("var CategoryCaptions = map[int]string{\n")
	for _, name := range catNames {
		cat := g.c.Categories[name]
		fmt.Fprintf(b, "\tCategoryUID%s: %q,\n", GoName(name), cat.Caption)
	}
	b.WriteString("}\n")

	return formatSource(b.String())
}

// observablesFile renders observable type_id lookup maps derived from the
// schema's observable annotations.
func (g *generator) observablesFile() ([]byte, error) {
	b := &strings.Builder{}
	g.header(b, g.opts.ObjectsPackage)

	writeMap := func(name, doc string, entries map[string]int) {
		keys := make([]string, 0, len(entries))
		for k := range entries {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		writeComment(b, doc)
		fmt.Fprintf(b, "var %s = map[string]int{\n", name)
		for _, k := range keys {
			fmt.Fprintf(b, "\t%q: %d,\n", k, entries[k])
		}
		b.WriteString("}\n\n")
	}

	byAttr := map[string]int{}
	for name, attr := range g.c.Dictionary.Attributes {
		if attr != nil && attr.Observable != 0 {
			byAttr[name] = attr.Observable
		}
	}
	writeMap("ObservableTypeIDByAttribute",
		"ObservableTypeIDByAttribute maps OCSF dictionary attribute names to the observable type_id assigned to that attribute.",
		byAttr)

	byType := map[string]int{}
	for name, typ := range g.c.Dictionary.Types.Attributes {
		if typ.Observable != 0 {
			byType[name] = typ.Observable
		}
	}
	writeMap("ObservableTypeIDByDictionaryType",
		"ObservableTypeIDByDictionaryType maps OCSF dictionary type names (e.g. \"ip_t\") to the observable type_id assigned to values of that type.",
		byType)

	byObject := map[string]int{}
	for name, obj := range g.c.Objects {
		if !obj.Hidden && obj.Observable != 0 {
			byObject[name] = obj.Observable
		}
	}
	writeMap("ObservableTypeIDByObject",
		"ObservableTypeIDByObject maps OCSF object names to the observable type_id assigned to that object.",
		byObject)

	return formatSource(b.String())
}

// ocsfdataFiles renders the embedded compiled schema: an indented JSON
// serialization (uncompressed, so it is scannable and diffs are reviewable)
// plus its go:embed accessor. Map keys marshal sorted, so output is
// deterministic.
func (g *generator) ocsfdataFiles() (map[string][]byte, error) {
	raw, err := json.MarshalIndent(g.c, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshaling compiled schema: %w", err)
	}
	raw = append(raw, '\n')

	b := &strings.Builder{}
	fmt.Fprintf(b, "// Code generated by ocsfgen from OCSF schema v%s; DO NOT EDIT.\n", g.c.Version)
	b.WriteString("// Source: https://github.com/ocsf/ocsf-schema\n\n")
	b.WriteString("// Package ocsfdata embeds the compiled OCSF schema so that consumers (e.g.\n")
	b.WriteString("// the validate package) can work with full schema metadata at runtime\n")
	b.WriteString("// without an OCSF schema checkout on disk.\n")
	b.WriteString("package ocsfdata\n\n")
	b.WriteString("import (\n\t_ \"embed\"\n\t\"encoding/json\"\n\t\"fmt\"\n\t\"sync\"\n\n")
	fmt.Fprintf(b, "\t%q\n)\n\n", g.opts.SchemaImportPath)
	b.WriteString("//go:embed schema.json\nvar data []byte\n\n")
	b.WriteString("var (\n\tonce    sync.Once\n\tcached  *schema.CompiledSchema\n\tloadErr error\n)\n\n")
	b.WriteString("// Schema returns the embedded compiled OCSF schema. The result is decoded\n")
	b.WriteString("// once and shared; treat it as read-only.\n")
	b.WriteString("func Schema() (*schema.CompiledSchema, error) {\n")
	b.WriteString("\tonce.Do(func() {\n")
	b.WriteString("\t\tc := &schema.CompiledSchema{}\n")
	b.WriteString("\t\tif err := json.Unmarshal(data, c); err != nil {\n\t\t\tloadErr = fmt.Errorf(\"ocsfdata: decoding embedded schema: %w\", err)\n\t\t\treturn\n\t\t}\n")
	b.WriteString("\t\tcached = c\n\t})\n")
	b.WriteString("\treturn cached, loadErr\n}\n\n")
	b.WriteString("// MustSchema is Schema, panicking on error. The embedded data is generated\n")
	b.WriteString("// with the module, so an error indicates a corrupted build.\n")
	b.WriteString("func MustSchema() *schema.CompiledSchema {\n")
	b.WriteString("\tc, err := Schema()\n\tif err != nil {\n\t\tpanic(err)\n\t}\n\treturn c\n}\n")

	src, err := formatSource(b.String())
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		"ocsfdata/schema.json": raw,
		"ocsfdata/ocsfdata.go": src,
	}, nil
}

// writeStruct renders one struct plus the enum constants of its attributes.
func (g *generator) writeStruct(b *strings.Builder, goName, docFirst, description string, deprecated *schema.Deprecation, attrs map[string]*schema.Attribute, inEvents bool) error {
	names := make([]string, 0, len(attrs))
	for name := range attrs {
		names = append(names, name)
	}
	sort.Strings(names)

	writeComment(b, docFirst+" "+cleanText(description))
	if deprecated != nil {
		b.WriteString("//\n")
		writeComment(b, "Deprecated: "+cleanText(deprecated.Message))
	}
	fmt.Fprintf(b, "type %s struct {\n", goName)

	fieldNames := map[string]string{}
	for _, name := range names {
		attr := attrs[name]
		fieldName := GoName(name)
		if prev, ok := fieldNames[fieldName]; ok {
			return fmt.Errorf("field name collision: %s and %s both map to %s", prev, name, fieldName)
		}
		fieldNames[fieldName] = name

		goType, err := g.goType(attr, inEvents)
		if err != nil {
			return fmt.Errorf("attribute %s: %w", name, err)
		}

		if desc := cleanText(attr.Description); desc != "" {
			writeIndentedComment(b, desc)
		}
		if attr.Deprecated != nil {
			b.WriteString("\t//\n")
			writeIndentedComment(b, "Deprecated: "+cleanText(attr.Deprecated.Message))
		}
		tag := name
		if !alwaysPresent(attr) {
			tag += ",omitempty"
		}
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", fieldName, goType, tag)
	}
	b.WriteString("}\n\n")

	for _, name := range names {
		attr := attrs[name]
		if len(attr.Enum) == 0 || name == "class_uid" || name == "category_uid" {
			continue
		}
		prefix := goName + GoName(name)
		owner := fmt.Sprintf("%s.%s (%s)", goName, GoName(name), attr.Caption)
		if err := g.writeEnum(b, prefix, owner, attr); err != nil {
			return fmt.Errorf("attribute %s enum: %w", name, err)
		}
	}
	return nil
}

// writeEnum renders the enum constants for one attribute as
// <prefix><Caption> = <value>, followed by a <prefix>Captions lookup map.
func (g *generator) writeEnum(b *strings.Builder, prefix, owner string, attr *schema.Attribute) error {
	type member struct {
		key     string
		value   int
		caption string
		desc    string
	}
	members := make([]member, 0, len(attr.Enum))
	numeric := true
	for key, m := range attr.Enum {
		v, err := strconv.Atoi(key)
		if err != nil {
			numeric = false
		}
		members = append(members, member{key, v, m.Caption, m.Description})
	}
	if numeric {
		sort.Slice(members, func(i, j int) bool { return members[i].value < members[j].value })
	} else {
		sort.Slice(members, func(i, j int) bool { return members[i].key < members[j].key })
	}

	fmt.Fprintf(b, "// %s values for %s.\nconst (\n", prefix, owner)
	used := map[string]bool{}
	for _, m := range members {
		ident := EnumIdent(m.caption)
		if ident == "" || used[prefix+ident] {
			ident += "Value" + EnumIdent(m.key)
		}
		if used[prefix+ident] {
			return fmt.Errorf("enum constant collision on %s%s", prefix, ident)
		}
		used[prefix+ident] = true
		if desc := cleanText(m.desc); desc != "" {
			writeIndentedComment(b, desc)
		}
		if numeric {
			fmt.Fprintf(b, "\t%s%s = %d\n", prefix, ident, m.value)
		} else {
			fmt.Fprintf(b, "\t%s%s = %q\n", prefix, ident, m.key)
		}
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(b, "// %sCaptions maps %s values to their captions.\n", prefix, owner)
	if numeric {
		fmt.Fprintf(b, "var %sCaptions = map[int]string{\n", prefix)
		for _, m := range members {
			fmt.Fprintf(b, "\t%d: %q,\n", m.value, m.caption)
		}
	} else {
		fmt.Fprintf(b, "var %sCaptions = map[string]string{\n", prefix)
		for _, m := range members {
			fmt.Fprintf(b, "\t%q: %q,\n", m.key, m.caption)
		}
	}
	b.WriteString("}\n\n")
	return nil
}

// goType maps a compiled attribute to a Go type.
func (g *generator) goType(attr *schema.Attribute, inEvents bool) (string, error) {
	t := attr.Type
	if t == "" {
		// Attribute missing from the dictionary (compile emitted a warning).
		return "any", nil
	}

	// The generic "object" type is an unordered collection of attributes.
	if t == "object" {
		if attr.IsArray {
			return "[]map[string]any", nil
		}
		return "map[string]any", nil
	}

	if obj, ok := g.c.Objects[t]; ok {
		name := GoName(obj.Name)
		if inEvents {
			name = g.opts.ObjectsPackage + "." + name
		}
		if attr.IsArray {
			return "[]" + name, nil
		}
		return "*" + name, nil
	}

	var elem string
	switch root := g.c.RootScalarType(t); root {
	case "string_t":
		elem = "string"
	case "integer_t":
		elem = "int"
	case "long_t":
		elem = "int64"
	case "float_t":
		elem = "float64"
	case "boolean_t":
		if attr.IsArray {
			return "[]bool", nil
		}
		// Pointer so that an explicit false survives omitempty.
		return "*bool", nil
	case "json_t":
		if attr.IsArray {
			return "[]any", nil
		}
		return "any", nil
	default:
		return "", fmt.Errorf("unmapped type %q (root %q)", t, root)
	}
	if attr.IsArray {
		return "[]" + elem, nil
	}
	return elem, nil
}

var htmlTag = regexp.MustCompile(`<[^>]*>`)
var spaces = regexp.MustCompile(`\s+`)

// cleanText strips HTML markup and normalizes whitespace in schema
// descriptions.
func cleanText(s string) string {
	s = htmlTag.ReplaceAllString(s, " ")
	s = html.UnescapeString(s)
	return strings.TrimSpace(spaces.ReplaceAllString(s, " "))
}

func writeComment(b *strings.Builder, text string) {
	for _, line := range wrap(text, 96) {
		fmt.Fprintf(b, "// %s\n", line)
	}
}

func writeIndentedComment(b *strings.Builder, text string) {
	for _, line := range wrap(text, 92) {
		fmt.Fprintf(b, "\t// %s\n", line)
	}
}

func wrap(text string, width int) []string {
	words := strings.Fields(text)
	if len(words) == 0 {
		return nil
	}
	var lines []string
	line := words[0]
	for _, w := range words[1:] {
		if len(line)+1+len(w) > width {
			lines = append(lines, line)
			line = w
			continue
		}
		line += " " + w
	}
	return append(lines, line)
}

func formatSource(src string) ([]byte, error) {
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("formatting generated source: %w", err)
	}
	return out, nil
}

// alwaysPresent reports whether an attribute must appear in every event or
// object, so its JSON tag omits omitempty. An attribute mixed in by a
// profile is required only when the event declares that profile in
// metadata.profiles, so it stays omitempty: otherwise an event without the
// profile would carry it as null.
func alwaysPresent(attr *schema.Attribute) bool {
	if attr.Requirement != schema.RequirementRequired {
		return false
	}
	return attr.Profile == nil && !strings.HasPrefix(attr.Source, "profile:")
}
